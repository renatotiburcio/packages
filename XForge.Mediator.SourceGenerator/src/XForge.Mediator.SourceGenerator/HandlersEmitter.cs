using System.Text;
using Microsoft.CodeAnalysis;

namespace XForge.Mediator.Generators;

/// <summary>Um handler descoberto: tipo concreto + par (request, resposta).</summary>
internal sealed record HandlerModel(
    INamedTypeSymbol HandlerType,
    ITypeSymbol RequestType,
    ITypeSymbol ResponseType);

/// <summary>
/// Emite o cÃ³digo C# do mediator gerado (emissÃ£o por string, como o Mediator.SourceGenerator
/// faz com templates): interface do wrapper, wrapper tipado por handler com cadeia de behaviors,
/// registry de dispatch, sender implementando <c>ISender</c> e a extensÃ£o de DI
/// <c>AddXForgeMediatorGenerated</c>.
/// </summary>
internal static class HandlersEmitter
{
    private const string GeneratedNamespace = "XForge.Mediator.Generated";
    private const string RegistryName = "XForgeGeneratedRegistry";

    public static void Emit(
        SourceProductionContext context,
        List<HandlerModel> handlers,
        Compilation compilation)
    {
        if (handlers.Count == 0)
        {
            return;
        }

        var source = BuildSource(handlers);
        context.AddSource("XForgeGeneratedMediator.g.cs", source);
    }

    private static string BuildSource(List<HandlerModel> handlers)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using Microsoft.Extensions.DependencyInjection;");
        builder.AppendLine("using Microsoft.Extensions.DependencyInjection.Extensions;");
        builder.AppendLine("using System;");
        builder.AppendLine("using System.Collections.Generic;");
        builder.AppendLine("using System.Linq;");
        builder.AppendLine("using System.Threading;");
        builder.AppendLine("using System.Threading.Tasks;");
        builder.AppendLine();
        builder.AppendLine($"namespace {GeneratedNamespace};");
        builder.AppendLine();

        builder.AppendLine("/// <summary>Wrapper tipado por par (request, resposta) â€” gerado em compile-time.</summary>");
        builder.AppendLine("internal interface IXForgeHandlerWrapper");
        builder.AppendLine("{");
        builder.AppendLine("    ValueTask<object?> HandleAsync(object request, IServiceProvider serviceProvider, CancellationToken cancellationToken);");
        builder.AppendLine("}");
        builder.AppendLine();

        builder.AppendLine("/// <summary>Registry de dispatch gerado em compile-time.</summary>");
        builder.AppendLine($"internal static class {RegistryName}");
        builder.AppendLine("{");
        builder.AppendLine("    private static readonly Dictionary<(Type Request, Type Response), Func<IXForgeHandlerWrapper>> Factories = new();");
        builder.AppendLine("    private static bool _initialized;");
        builder.AppendLine();
        builder.AppendLine("    internal static void Initialize()");
        builder.AppendLine("    {");
        builder.AppendLine("        if (_initialized)");
        builder.AppendLine("        {");
        builder.AppendLine("            return;");
        builder.AppendLine("        }");
        foreach (var handler in handlers.GroupBy(Unique).Select(group => group.First()))
        {
            builder.AppendLine($"        Factories[(typeof({GlobalName(handler.RequestType)}), typeof({GlobalName(handler.ResponseType)}))] = () => new {WrapperName(handler)}();");
        }
        builder.AppendLine("        _initialized = true;");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    internal static IXForgeHandlerWrapper? Resolve(Type requestType, Type responseType)");
        builder.AppendLine("    {");
        builder.AppendLine("        Initialize();");
        builder.AppendLine("        return Factories.TryGetValue((requestType, responseType), out var create) ? create() : null;");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    internal static void RegisterHandlers(IServiceCollection services)");
        builder.AppendLine("    {");
        foreach (var handler in handlers.GroupBy(Unique).Select(group => group.First()))
        {
            builder.AppendLine($"        services.TryAddTransient(typeof({GlobalName(handler.HandlerType)}));");
        }
        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine();

        foreach (var handler in handlers.GroupBy(Unique).Select(group => group.First()))
        {
            builder.AppendLine(EmitWrapper(handler));
        }

        builder.AppendLine(EmitSender());
        builder.AppendLine(EmitExtensions(handlers));

        return builder.ToString();
    }

    /// <summary>
    /// <code>
    /// internal sealed class MyHandlerWrapper : IXForgeHandlerWrapper
    /// {
    ///     public async ValueTask&lt;object?&gt; HandleAsync(object request, IServiceProvider serviceProvider, CancellationToken cancellationToken)
    ///     {
    ///         var handler = (MyHandler)serviceProvider.GetRequiredService(typeof(MyHandler));
    ///         var behaviors = (IPipelineBehavior&lt;MyRequest, MyResponse&gt;[])serviceProvider.GetServices(
    ///             typeof(IPipelineBehavior&lt;MyRequest, MyResponse&gt;));
    ///         RequestHandlerDelegate&lt;MyResponse&gt; next = cancellationToken =&gt; handler.Handle((MyRequest)request, cancellationToken);
    ///         for (var i = behaviors.Length - 1; i &gt;= 0; i--)
    ///         {
    ///             var behavior = behaviors[i];
    ///             var previous = next;
    ///             next = cancellationToken =&gt; behavior.Handle((MyRequest)request, previous, cancellationToken);
    ///         }
    ///         return await next(cancellationToken);
    ///     }
    /// }
    /// </code>
    /// </summary>
    private static string EmitWrapper(HandlerModel handler)
    {
        var request = GlobalName(handler.RequestType);
        var response = GlobalName(handler.ResponseType);
        var handlerType = GlobalName(handler.HandlerType);
        var builder = new StringBuilder();

        builder.AppendLine("/// <summary>Wrapper tipado do handler " + handlerType + ".</summary>");
        builder.AppendLine($"internal sealed class {WrapperName(handler)} : IXForgeHandlerWrapper");
        builder.AppendLine("{");
        builder.AppendLine("    public async ValueTask<object?> HandleAsync(object request, IServiceProvider serviceProvider, CancellationToken cancellationToken)");
        builder.AppendLine("    {");
        builder.AppendLine($"        var handler = ({handlerType})serviceProvider.GetRequiredService(typeof({handlerType}));");
        builder.AppendLine($"        var behaviors = (global::XForge.Mediator.IPipelineBehavior<{request}, {response}>[])serviceProvider.GetServices(");
        builder.AppendLine($"            typeof(global::XForge.Mediator.IPipelineBehavior<{request}, {response}>));");
        builder.AppendLine($"        global::XForge.Mediator.RequestHandlerDelegate<{response}> next = token => handler.Handle(({request})request, token);");
        builder.AppendLine("        for (var i = behaviors.Length - 1; i >= 0; i--)");
        builder.AppendLine("        {");
        builder.AppendLine("            var behavior = behaviors[i];");
        builder.AppendLine("            var previous = next;");
        builder.AppendLine($"            next = token => behavior.Handle(({request})request, previous, token);");
        builder.AppendLine("        }");
        builder.AppendLine("        return await next(cancellationToken);");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        builder.AppendLine();
        return builder.ToString();
    }

    private static string EmitSender()
    {
        var builder = new StringBuilder();
        builder.AppendLine("/// <summary>Sender gerado em compile-time â€” dispatch por wrappers tipados sem reflection.</summary>");
        builder.AppendLine("public sealed class XForgeGeneratedSender : global::XForge.Mediator.ISender");
        builder.AppendLine("{");
        builder.AppendLine("    private readonly IServiceProvider _serviceProvider;");
        builder.AppendLine();
        builder.AppendLine("    public XForgeGeneratedSender(IServiceProvider serviceProvider)");
        builder.AppendLine("    {");
        builder.AppendLine("        _serviceProvider = serviceProvider;");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    public ValueTask<TResponse> Send<TResponse>(global::XForge.Mediator.IRequest<TResponse> request, CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine($"        var wrapper = {RegistryName}.Resolve(request.GetType(), typeof(TResponse));");
        builder.AppendLine("        if (wrapper is null)");
        builder.AppendLine("        {");
        builder.AppendLine("            throw new global::XForge.Mediator.HandlerNotFoundException(request.GetType(), typeof(TResponse));");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        return Continue(wrapper.HandleAsync(request, _serviceProvider, cancellationToken));");
        builder.AppendLine();
        builder.AppendLine("        static async ValueTask<TResponse> Continue(ValueTask<object?> task)");
        builder.AppendLine("        {");
        builder.AppendLine("            var result = await task;");
        builder.AppendLine("            return (TResponse)result!;");
        builder.AppendLine("        }");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    public ValueTask<TResponse> Send<TResponse>(object request, CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        return request is global::XForge.Mediator.IRequest<TResponse> typed");
        builder.AppendLine("            ? Send(typed, cancellationToken)");
        builder.AppendLine("            : throw new global::XForge.Mediator.HandlerNotFoundException(request.GetType(), typeof(TResponse));");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    public ValueTask<object?> Send(object request, CancellationToken cancellationToken = default)");
        builder.AppendLine("    {");
        builder.AppendLine("        // caminho nao-tipado: descobre o IRequest<TResponse> fechado por reflection (o caminho");
        builder.AppendLine("        // tipado Send<TResponse>(IRequest<TResponse>) segue sem reflection)");
        builder.AppendLine("        var requestInterface = request.GetType()");
        builder.AppendLine("            .GetInterfaces()");
        builder.AppendLine("            .FirstOrDefault(candidate => candidate.IsGenericType &&");
        builder.AppendLine("                candidate.GetGenericTypeDefinition() == typeof(global::XForge.Mediator.IRequest<>));");
        builder.AppendLine("        if (requestInterface is null)");
        builder.AppendLine("        {");
        builder.AppendLine("            throw new global::XForge.Mediator.HandlerNotFoundException(request.GetType());");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        var responseType = requestInterface.GetGenericArguments()[0];");
        builder.AppendLine("        var sendMethod = typeof(XForgeGeneratedSender).GetMethod(nameof(Send), new[] { requestInterface, typeof(CancellationToken) })!;");
        builder.AppendLine("        var closed = sendMethod.MakeGenericMethod(responseType);");
        builder.AppendLine("        return new ValueTask<object?>(closed.Invoke(this, new object[] { request, cancellationToken })!);");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    public IAsyncEnumerable<TResponse> CreateStream<TResponse>(global::XForge.Mediator.IStreamRequest<TResponse> request, CancellationToken cancellationToken = default)");
        builder.AppendLine("        => throw new NotSupportedException(\"Streams: use o pacote de runtime XForge.Mediator (AddXForgeMediator) â€” o source generator cobre apenas requests em v0.1.\");");
        builder.AppendLine();
        builder.AppendLine("    public IAsyncEnumerable<object?> CreateStream(object request, CancellationToken cancellationToken = default)");
        builder.AppendLine("        => throw new NotSupportedException(\"Streams: use o pacote de runtime XForge.Mediator (AddXForgeMediator) â€” o source generator cobre apenas requests em v0.1.\");");
        builder.AppendLine("}");
        builder.AppendLine();
        return builder.ToString();
    }

    private static string EmitExtensions(List<HandlerModel> handlers)
    {
        var builder = new StringBuilder();
        builder.AppendLine("/// <summary>ExtensÃµes de DI do mediator gerado.</summary>");
        builder.AppendLine("public static class XForgeMediatorGeneratedExtensions");
        builder.AppendLine("{");
        builder.AppendLine("    /// <summary>");
        builder.AppendLine("    /// Registra os handlers descobertos em compile-time e o sender gerado.");
        builder.AppendLine("    /// Substitui o scanning do <c>AddXForgeMediator</c> do pacote de runtime.");
        builder.AppendLine("    /// </summary>");
        builder.AppendLine("    public static IServiceCollection AddXForgeMediatorGenerated(this IServiceCollection services)");
        builder.AppendLine("    {");
        builder.AppendLine($"        {RegistryName}.RegisterHandlers(services);");
        builder.AppendLine($"        {RegistryName}.Initialize();");
        builder.AppendLine("        services.TryAddSingleton<global::XForge.Mediator.ISender, XForgeGeneratedSender>();");
        builder.AppendLine("        return services;");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static string Unique(HandlerModel handler) =>
        GlobalName(handler.RequestType) + "|" + GlobalName(handler.ResponseType);

    private static string WrapperName(HandlerModel handler) =>
        GlobalName(handler.HandlerType).Replace("global::", string.Empty).Replace(".", "_") + "_Wrapper";

    private static string GlobalName(ITypeSymbol type) =>
        type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
}


