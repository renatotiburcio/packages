const fs = require('fs');
const path = require('path');
const target = path.join(__dirname, 'gen_docs.js');
const DASH = '\u2014';
const lines = [];

lines.push("'use strict';");
lines.push('');
lines.push('const fs = require("fs");');
lines.push('const path = require("path");');
lines.push('');
lines.push('const COMPONENTS_ROOT = path.join("D:\\\\dev\\\\XForge\\\\components\\\\src\\\\XForge.DesignSystem\\\\Components");');
lines.push('const DOCS_ROOT = path.join("D:\\\\dev\\\\XForge\\\\components\\\\src\\\\XForge.DesignSystem.Docs\\\\Components\\\\Pages");');
lines.push('const SKIP = new Set(["XFComponentGrid"]);');
lines.push('const DASH = "' + DASH + '";');
lines.push('');
lines.push('function walkDir(dir, ext, results = []) {');
lines.push('  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {');
lines.push('    const full = path.join(dir, entry.name);');
lines.push('    if (entry.isDirectory()) walkDir(full, ext, results);');
lines.push('    else if (entry.name.endsWith(ext)) results.push(full);');
lines.push('  }');
lines.push('  return results;');
lines.push('}');
lines.push('');
lines.push('function getDocName(c) { return c.startsWith("XF") ? c.slice(2) : c; }');
lines.push('');
lines.push('function getExistingDocs() {');
lines.push('  if (!fs.existsSync(DOCS_ROOT)) return new Set();');
lines.push('  const docs = new Set();');
lines.push('  for (const f of fs.readdirSync(DOCS_ROOT)) {');
lines.push('    if (f.endsWith("Docs.razor")) docs.add(f.replace("Docs.razor", ""));');
lines.push('  }');
lines.push('  return docs;');
lines.push('}');
lines.push('');
lines.push('function extractNs(s) { const m = s.match(/namespace\\s+([\\w.]+)/); return m ? m[1] : null; }');
lines.push('function extractNsR(s) { const m = s.match(/@namespace\\s+([\\w.]+)/); return m ? m[1] : null; }');
lines.push('');
lines.push('function extractParams(s) {');
lines.push('  const params = [];');
lines.push('  const re = /\\[Parameter\\]\\s*(?:public\\s+)?([\\w<>\\?\\[\\],\\s]+?)\\s+(\\w+)\\s*\\{\\s*get;\\s*set;\\s*\\}(?:\\s*=\\s*(.+?))?;/g;');
lines.push('  let m;');
lines.push('  while ((m = re.exec(s)) !== null) {');
lines.push('    let def = m[3] ? m[3].trim() : DASH; if (def === "") def = DASH;');
lines.push('    params.push({ name: m[2], type: m[1].trim(), default: def });');
lines.push('  }');
lines.push('  return params;');
lines.push('}');
lines.push('');
lines.push('function getCat(rp) { const p = rp.split(path.sep); return p.length <= 1 ? "General" : p[0]; }');
lines.push('');
lines.push('function buildParamRows(params) {');
lines.push('  if (!params.length) return \'        new("\' + DASH + \'", "\' + DASH + \'", "\' + DASH + \'", T("No parameters documented.", "No parameters documented."))\';');
lines.push('  return params.map(p => {');
lines.push('    const dv = p.default === DASH ? \'T("\' + DASH + \'", "\' + DASH + \'")\' : \'"\' + p.default + \'"\';');
lines.push('    return \'        new("\' + p.name + \'", "\' + p.type + \'", \' + dv + \', T("\' + p.name + \' parameter.", "\' + p.name + \' parameter."))\';');
lines.push('  }).join(",\\n");');
lines.push('}');

fs.writeFileSync(target, lines.join('\n'), 'utf-8');
console.log('Part 1 written to gen_docs.js');