using System.Text;

namespace XForge.AssetsGenerator;

/// <summary>
/// Generates one .cs file per (Variant, Size) combination. Each .cs contains N inner
/// classes (one per icon name). Aligns with FluentUI.AssetsGenerator.IconsCodeGenerator.
/// </summary>
public static class IconsCodeGenerator
{
    public static int Generate(GeneratorSettings settings)
    {
        if (!System.IO.Directory.Exists(settings.Assets))
        {
            Console.Error.WriteLine($"ERROR: assets path not found: {settings.Assets}");
            return 1;
        }

        System.IO.Directory.CreateDirectory(settings.Target!);
        var svgFiles = System.IO.Directory.EnumerateFiles(settings.Assets, "*.svg", System.IO.SearchOption.AllDirectories);
        var nameFilter = settings.Names?.Split(',', StringSplitOptions.RemoveEmptyEntries).ToHashSet();
        var sizeFilter = settings.Sizes?.Split(',', StringSplitOptions.RemoveEmptyEntries).Select(int.Parse).ToHashSet();
        var grouped = svgFiles.Select(ParseIcon).Where(i => i != null).Cast<Icon>()
            .Where(i => nameFilter == null || nameFilter.Contains(i.Name))
            .Where(i => sizeFilter == null || sizeFilter.Contains(i.Size))
            .GroupBy(i => $"{i.Variant}_{i.Size}");

        var count = 0;
        foreach (var group in grouped)
        {
            var sb = new StringBuilder();
            sb.AppendLine($"namespace {settings.Namespace};");
            sb.AppendLine();
            sb.AppendLine($"// Auto-generated by XForge.AssetsGenerator (T080) - {group.Count()} icons");
            foreach (var icon in group)
            {
                var svg = System.IO.File.ReadAllText(icon.SvgPath);
                sb.AppendLine($"public static class {icon.Name} {{ public const string Svg = @\"{svg}\"; }}");
                count++;
            }
            var path = System.IO.Path.Combine(settings.Target!, $"{group.Key}.cs");
            System.IO.File.WriteAllText(path, sb.ToString());
        }

        Console.WriteLine($"Generated {count} icons in {grouped.Count()} files");
        return 0;
    }

    private static Icon? ParseIcon(string svgPath)
    {
        var file = System.IO.Path.GetFileNameWithoutExtension(svgPath);
        var parts = file.Split('_');
        if (parts.Length < 3) return null;
        return new Icon
        {
            Name = parts[0],
            Variant = parts[1],
            Size = int.Parse(parts[2]),
            SvgPath = svgPath,
        };
    }
}