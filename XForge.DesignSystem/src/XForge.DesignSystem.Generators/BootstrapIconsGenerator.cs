using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
namespace XForge.DesignSystem.Generators;
[Generator]
public class BootstrapIconsGenerator : ISourceGenerator
{
    public void Initialize(GeneratorInitializationContext context) { }
    public void Execute(GeneratorExecutionContext context)
    {
        var icons = LoadIcons(context);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> by BootstrapIconsGenerator");
        sb.AppendLine("namespace XForge.DesignSystem.Generated;");
        sb.AppendLine("public static class BootstrapIcons");
        sb.AppendLine("{");
        foreach (var name in icons.Select(i => i.Name).Distinct().OrderBy(n => n)) sb.AppendLine($"    public const string {Sanitize(name)} = \\"{name}\\";");
        sb.AppendLine("}");
        context.AddSource("BootstrapIcons.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }
    private IEnumerable<IconEntry> LoadIcons(GeneratorExecutionContext ctx)
    {
        var paths = ctx.AdditionalFiles.Where(a => a.Path.EndsWith(".svg")).Select(a => a.Path);
        foreach (var p in paths) yield return new IconEntry(Path.GetFileNameWithoutExtension(p), "");
    }
    private static string Sanitize(string s) { var sb = new StringBuilder(); foreach (var c in s) sb.Append(char.IsLetterOrDigit(c) ? char.ToUpperInvariant(c) : "_"); return sb.ToString(); }
    private record IconEntry(string Name, string Content);
}