    /// <summary>
    /// Generates a report definition from the current natural language query.
    /// </summary>
    public async Task GenerateReportAsync()
    {
        if (!CanSend)
            return;

        _errorText = null;
        _reportDefinition = null;
        _isGenerating = true;
        StateHasChanged();

        _cts?.Dispose();
        _cts = new CancellationTokenSource();
        var ct = _cts.Token;

        try
        {
            var systemPrompt = SystemPrompt ?? DefaultSystemPrompt;

            if (AvailableFields is { Count: > 0 })
            {
                var fieldList = string.Join(", ", AvailableFields.Select(f =>
                    $"{f.Name} ({f.DisplayName}, {f.DataType}{(f.IsRequired ? ", obrigatório" : "")})"));
                systemPrompt += $"\n\nCampos disponíveis: {fieldList}";
            }

            systemPrompt += $"\n\nFormato preferido: {_selectedFormat}";

            var request = new AiChatRequest
            {
                Messages = new[]
                {
                    new AiMessage
                    {
                        Role = AiRole.User,
                        Content = _query!.Trim(),
                        Timestamp = DateTimeOffset.UtcNow
                    }
                },
                SystemPrompt = systemPrompt,
                Temperature = 0.3
            };

            var response = await Provider!.CompleteAsync(request, ct);
            var jsonContent = ExtractJson(response.Message.Content);

            var definition = JsonSerializer.Deserialize<XFAiReportDefinition>(jsonContent, JsonOptions);

            if (definition is not null)
            {
                definition.NaturalLanguageQuery = _query.Trim();

                // Ensure format is respected if AI didn't override
                if (SupportedFormats is { Count: > 0 } && !SupportedFormats.Contains(definition.Format))
                {
                    definition.Format = _selectedFormat;
                }

                _reportDefinition = definition;

                if (OnReportGenerated.HasDelegate)
                {
                    await OnReportGenerated.InvokeAsync(definition);
                }
            }
            else
            {
                _errorText = "Não foi possível gerar a definição do relatório. Tente reformular sua solicitação.";
                if (OnError.HasDelegate)
                {
                    await OnError.InvokeAsync(_errorText);
                }
            }
        }
        catch (OperationCanceledException)
        {
            // User cancelled — no error to show
        }
        catch (JsonException)
        {
            _errorText = "A resposta da IA não está no formato esperado. Tente novamente.";
            if (OnError.HasDelegate)
            {
                await OnError.InvokeAsync(_errorText);
            }
        }
        catch (Exception ex)
        {
            _errorText = ex.Message;
            if (OnError.HasDelegate)
            {
                await OnError.InvokeAsync(ex.Message);
            }
        }
        finally
        {
            _isGenerating = false;
            _cts?.Dispose();
            _cts = null;
            StateHasChanged();
        }
    }

    /// <summary>
    /// Clears the current report definition and resets the component to the empty state.
    /// </summary>
    public void Clear()
    {
