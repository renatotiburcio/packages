namespace XForge.DesignSystem.Components.AI.Avatars;

/// <summary>
/// Type of proactive insight.
/// </summary>
public enum XFAiInsightType
{
    /// <summary>Suggested next action.</summary>
    Suggestion,
    /// <summary>Warning about potential issue.</summary>
    Warning,
    /// <summary>Informational insight.</summary>
    Info,
    /// <summary>Optimization recommendation.</summary>
    Optimization,
    /// <summary>Anomaly detected in user behavior.</summary>
    Anomaly,
    /// <summary>Reminder about pending task.</summary>
    Reminder
}

/// <summary>
/// Priority level for proactive insights.
/// </summary>
public enum XFAiInsightPriority
{
    /// <summary>Low priority — show when convenient.</summary>
    Low,
    /// <summary>Medium priority — show soon.</summary>
    Medium,
    /// <summary>High priority — show immediately.</summary>
    High,
    /// <summary>Critical — interrupt user workflow.</summary>
    Critical
}

/// <summary>
/// A proactive insight generated by the AI agent based on user behavior.
/// </summary>
public sealed record XFAiProactiveInsightItem
{
    /// <summary>Unique identifier.</summary>
    public string Id { get; init; } = Guid.NewGuid().ToString("N");

    /// <summary>Type of insight.</summary>
    public required XFAiInsightType Type { get; init; }

    /// <summary>Priority level.</summary>
    public XFAiInsightPriority Priority { get; init; } = XFAiInsightPriority.Medium;

    /// <summary>Title/heading of the insight.</summary>
    public required string Title { get; init; }

    /// <summary>Detailed description.</summary>
    public required string Description { get; init; }

    /// <summary>Optional action label (e.g., "Ver detalhes", "Corrigir").</summary>
    public string? ActionLabel { get; init; }

    /// <summary>Optional action route or callback identifier.</summary>
    public string? ActionRoute { get; init; }

    /// <summary>Icon name from icon catalog.</summary>
    public string? IconName { get; init; }

    /// <summary>Context that triggered this insight.</summary>
    public string? TriggerContext { get; init; }

    /// <summary>Confidence score (0.0–1.0).</summary>
    public double Confidence { get; init; } = 0.8;

    /// <summary>When this insight was generated.</summary>
    public DateTimeOffset GeneratedAt { get; init; } = DateTimeOffset.UtcNow;

    /// <summary>When this insight expires (null = no expiry).</summary>
    public DateTimeOffset? ExpiresAt { get; init; }

    /// <summary>Whether the user dismissed this insight.</summary>
    public bool IsDismissed { get; init; }
}
