using System.Collections.Generic;
using System.Text;

namespace XForge.DesignSystem.Components.Icon;

/// <summary>
/// In-process source generator stub. The real implementation lives in the
/// <c>XForge.DesignSystem.Generators</c> project and runs as an IIncrementalGenerator
/// at build time, scanning assemblies for <see cref="FluentUIComponentAttribute"/>.
/// This class is the manual fallback so the project compiles even when the generator
/// project is not referenced.
/// </summary>
public static class XFIconRegistryGenerator
{
    public static IReadOnlyDictionary<string, IReadOnlyList<string>> BuildIndex(
        IEnumerable<KeyValuePair<string, string[]>> componentUses)
    {
        var map = new Dictionary<string, IReadOnlyList<string>>();
        foreach (var (component, icons) in componentUses)
            map[component] = icons;
        return map;
    }

    public static string GenerateSource(
        IReadOnlyDictionary<string, IReadOnlyList<string>> index,
        string @namespace = "XForge.DesignSystem.Generated")
    {
        var sb = new StringBuilder();
        sb.AppendLine($"namespace {@namespace};");
        sb.AppendLine();
        sb.AppendLine($"// Auto-generated by XFIconRegistryGenerator (T087) - {index.Count} components");
        sb.AppendLine("public static class XFIconCatalogIndex {");
        foreach (var (component, icons) in index)
        {
            sb.AppendLine($"  public static readonly string[] {component}Icons = new[] {{");
            foreach (var icon in icons) sb.AppendLine($"    \"{icon}\",");
            sb.AppendLine("  };");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }
}